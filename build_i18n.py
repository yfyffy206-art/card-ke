HEADER = ("/* مولّد تلقائياً بواسطة build_i18n.py — لا تعدّله يدوياً.\n"
          "   مفتاح الترجمة = النص العربي الحرفي كما في الصفحات. */\n")


def js_escape(s):
    return (s.replace('\\', '\\\\').replace('"', '\\"')
             .replace('\n', '\\n').replace('\r', '\\r')
             .replace('\u2028', '\\u2028').replace('\u2029', '\\u2029'))


def main():
    os.makedirs(OUT, exist_ok=True)
    # حماية من تكرار المفاتيح (يُحتفظ بأول تعريف) — فالمفتاح العربي فريد في القاموس
    seen = set()
    rows = []
    for row in T:
        if row[0] in seen:
            continue
        seen.add(row[0])
        rows.append(row)
    for i, lang in enumerate(LANGS):
        lines = []
        for row in rows:
            key = row[0]
            val = row[i] if i < len(row) else row[0]
            lines.append('"%s":"%s"' % (js_escape(key), js_escape(val)))
        body = 'window.I18N=window.I18N||{};\nwindow.I18N.%s={\n' % lang
        body += ',\n'.join(lines) + '\n};\n'
        path = os.path.join(OUT, '%s.js' % lang)
        with open(path, 'w', encoding='utf-8') as f:
            f.write(HEADER + body)
        print('wrote %s (%d keys)' % (path, len(rows)))


if __name__ == '__main__':
    main()
